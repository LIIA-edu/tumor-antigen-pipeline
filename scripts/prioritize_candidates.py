
#!/usr/bin/env python3

import os
import re
import ast
import argparse
import pandas as pd


def parse_args():

    parser = argparse.ArgumentParser(
        description="Prioritize candidate tumor antigens using "
                    "HPA, epitope, cancer-sharing and antigen-type evidence."
    )

    parser.add_argument(
        "--candidates",
        required=True,
        help="Candidate CSV generated by SPECIFICITY"
    )

    parser.add_argument(
        "--hpa",
        required=True,
        help="HPA tissue specificity CSV"
    )

    parser.add_argument(
        "--epitopes",
        required=True,
        help="Epitope CSV"
    )

    parser.add_argument(
        "--binary-matrix",
        required=True,
        help="Binary gene-by-cancer matrix"
    )

    parser.add_argument(
        "--merged-summed-genes",
        required=True,
        help="Merged gene CSV containing antigen type information"
    )

    parser.add_argument(
        "--output",
        required=True,
        help="Output prioritized candidates CSV"
    )

    return parser.parse_args()


