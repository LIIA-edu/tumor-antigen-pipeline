def find_column(df, candidates, description):
    for column in candidates:
        if column in df.columns:
            return column

    raise ValueError(
        f"Could not find {description}.\n"
        f"Expected one of: {candidates}\n"
        f"Available columns: {list(df.columns)}"
    )


def normalize_gene(series):
    return (
        series.astype("string")
        .str.strip()
        .str.upper()
        .replace("", pd.NA)
    )


def parse_tissue_expression(value):
    if pd.isna(value):
        return {}

    try:
        parsed = ast.literal_eval(str(value))
        if isinstance(parsed, dict):
            return parsed

    except (ValueError, SyntaxError, TypeError):
        pass

    return {}


# HPA TISSUE FILTER HELPERS
def has_only_placenta_or_testis(value):
    tissues = parse_tissue_expression(value)

    if not tissues:
        return False
    allowed_tissues = {
        "placenta",
        "testis",
        "testes",
        "testicle"
    }

    return all(
        str(tissue).strip().lower() in allowed_tissues
        for tissue in tissues.keys()
    )


def has_low_expression(value):
    tissues = parse_tissue_expression(value)
    if not tissues:
        return False

    for expression in tissues.values():
        try:
            if float(expression) >= 10.0:
                return False

        except (ValueError, TypeError):
            return False

    return True


def aggregate_values(series):
    values = (
        series.dropna()
        .astype(str)
        .str.strip()
    )

    values = values[
        (values != "") &
        (values.str.lower() != "nan")
    ]

    return "; ".join(sorted(set(values)))


# 1. READ CANDIDATES
def read_candidates(path):
    df = pd.read_csv(path)

    gene_col = find_column(
        df,
        ["gene_name", "gene", "Gene_Name"],
        "candidate gene column"
    )

    df["gene_key"] = normalize_gene(df[gene_col])

    df = df.dropna(subset=["gene_key"])

    df = df.drop_duplicates(
        subset=["gene_key"]
    )

    return df


# 2. HPA FILTER
def filter_hpa(candidates, path):

    hpa = pd.read_csv(path)

    gene_col = find_column(
        hpa,
        ["hpa_gene_name", "gene_name", "gene"],
        "HPA gene column"
    )

    specificity_col = find_column(
        hpa,
        ["rna_tissue_specificity"],
        "HPA tissue specificity column"
    )

    hpa_columns = [
        "rna_tissue_specific_ntpm",
        "rna_single_cell_specificity",
        "rna_single_cell_specific_ntpm"
    ]

    for column in hpa_columns:

        if column not in hpa.columns:

            raise ValueError(
                f"Missing HPA column: {column}\n"
                f"Available columns: {list(hpa.columns)}"
            )

    hpa["gene_key"] = normalize_gene(
        hpa[gene_col]
    )

    hpa = hpa.dropna(
        subset=["gene_key"]
    )

    # Keep tissue specificity data
    hpa["HPA_specificity"] = (
        hpa[specificity_col]
        .fillna("")
        .astype(str)
    )

    specificity_normalized = (
        hpa["HPA_specificity"]
        .str.strip()
        .str.lower()
    )

    # EXCLUDE genes with Low tissue specificity.
    low_tissue_specificity = specificity_normalized.str.contains(
        r"low\s+tissue\s+specificity",
        regex=True,
        na=False
    )

    excluded_genes = hpa.loc[
        low_tissue_specificity,
        "gene_key"
    ].nunique()

    hpa = hpa[
        ~low_tissue_specificity
    ].copy()


    # Rule: Accept genes expressed exclusively
    # in placenta or testis, regardless of nTPM.

    placenta_or_testis = hpa[
        "rna_tissue_specific_ntpm"
    ].apply(
        has_only_placenta_or_testis
    )

    # Rule: Accept genes only when ALL listed
    # tissues have expression below 5.0 nTPM.

    low_ntpm = hpa[
        "rna_tissue_specific_ntpm"
    ].apply(
        has_low_expression
    )

    # Final selection: any one of the three rules.

    hpa["passes_HPA"] = (
        low_tissue_specificity |
        placenta_or_testis |
        low_ntpm
    )

    # Keep only records passing at least one criterion.
    hpa = hpa[
        hpa["passes_HPA"]
    ].copy()

    aggregation_columns = [
        "HPA_specificity"
    ] + hpa_columns

    aggregation = {
        column: aggregate_values
        for column in aggregation_columns
    }

    hpa = (
        hpa.groupby("gene_key")
        .agg(aggregation)
        .reset_index()
    )

    result = candidates.merge(
        hpa,
        on="gene_key",
        how="inner"
    )

    return result


# 3. EPITOPE FILTER
def filter_epitopes(candidates, path):
    epitopes = pd.read_csv(path)

    gene_col = find_column(
        epitopes,
        ["gene_name"],
        "epitope gene column"
    )

    epitope_id_col = find_column(
        epitopes,
        ["epitope_id_clean"],
        "clean epitope ID column"
    )

    epitopes["gene_key"] = normalize_gene(
        epitopes[gene_col]
    )

    epitopes = epitopes.dropna(
        subset=["gene_key", epitope_id_col]
    )

    # Count unique epitopes per gene.
    epitope_counts = (
        epitopes.groupby("gene_key")[epitope_id_col]
        .nunique()
        .reset_index(name="n_epitopes")
    )

    result = candidates.merge(
        epitope_counts,
        on="gene_key",
        how="inner"
    )

    return result


# 4. CANCER SHARING
def add_cancer_sharing(candidates, path):

    matrix = pd.read_csv(path)

    gene_col = find_column(
        matrix,
        ["Gene_Name", "gene_name", "gene"],
        "gene symbol column in binary matrix"
    )

    matrix["gene_key"] = normalize_gene(
        matrix[gene_col]
    )

    matrix = matrix.dropna(
        subset=["gene_key"]
    )

    metadata_columns = {
        "Gene_ID",
        "Gene_Name",
        "gene_name",
        "gene",
        "gene_key",
        "Epitope_Count",
    }

    cancer_columns = [
        col for col in matrix.columns
        if col not in metadata_columns
    ]

    if not cancer_columns:

        raise ValueError(
            "No cancer columns found in binary matrix."
        )

    for col in cancer_columns:

        matrix[col] = pd.to_numeric(
            matrix[col],
            errors="coerce"
        ).fillna(0)

    matrix = (
        matrix.groupby("gene_key")[cancer_columns]
        .max()
        .reset_index()
    )

    def get_cancers(row):
        return [
            cancer
            for cancer in cancer_columns
            if row[cancer] > 0
        ]

    matrix["cancers"] = matrix.apply(
        get_cancers,
        axis=1
    )
    matrix["n_cancers"] = (
        matrix["cancers"].apply(len)
    )
    matrix["cancers"] = (
        matrix["cancers"].apply(
            lambda x: "; ".join(x)
        )
    )

    result = candidates.merge(
        matrix[
            [
                "gene_key",
                "n_cancers",
                "cancers"
            ]
        ],
        on="gene_key",
        how="left"
    )

    result["n_cancers"] = (
        result["n_cancers"]
        .fillna(0)
        .astype(int)
    )

    result["cancers"] = (
        result["cancers"]
        .fillna("")
    )

    result["shared_across_cancers"] = (
        result["n_cancers"] > 1
    )

    shared_count = (
        result["shared_across_cancers"].sum()
    )

    return result


# 5. ADD ANTIGEN TYPE
def add_antigen_type(candidates, path):
    merged = pd.read_csv(path)

    gene_col = find_column(
        merged,
        ["gene_name", "Gene_Name", "gene", "Gene", "gene_key"],
        "gene column in merged summed genes file"
    )
    type_col = find_column(
        merged,
        ["type", "antigen_type", "antigens_type"],
        "antigen type column in merged summed genes file"
    )
    merged["gene_key"] = normalize_gene(
        merged[gene_col]
    )
    merged = merged.dropna(
        subset=["gene_key"]
    )
    type_mapping = merged[
        ["gene_key", type_col]
    ].copy()

    type_mapping[type_col] = (
        type_mapping[type_col]
        .fillna("")
        .astype(str)
        .str.strip()
    )
    type_mapping = (
        type_mapping.groupby("gene_key")[type_col]
        .apply(aggregate_values)
        .reset_index(name="type")
    )

    candidates = candidates.drop(
        columns=["type"],
        errors="ignore"
    )

    result = candidates.merge(
        type_mapping,
        on="gene_key",
        how="left"
    )

    result["type"] = (
        result["type"]
        .fillna("")
    )

    matched = (
        result["type"].astype(str).str.strip() != ""
    ).sum()

    return result


def save_results(candidates, output):

    output_columns = [
        "gene_key",
        "type",
        "HPA_specificity",
        "rna_tissue_specific_ntpm",
        "rna_single_cell_specificity",
        "rna_single_cell_specific_ntpm",
        "n_epitopes",
        "n_cancers",
        "cancers",
        "shared_across_cancers",
    ]

    final = candidates[
        output_columns
    ].copy()

    final = final.rename(
        columns={
            "gene_key": "gene"
        }
    )

    final = final.sort_values(
        by=[
            "shared_across_cancers",
            "n_cancers",
            "n_epitopes"
        ],
        ascending=[
            False,
            False,
            False
        ]
    )

    final.to_csv(
        output,
        index=False
    )


def main():

    args = parse_args()

    os.makedirs(
        os.path.dirname(
            os.path.abspath(args.output)
        ),
        exist_ok=True
    )

    # 1. Initial candidates

    candidates = read_candidates(
        args.candidates
    )

    # 2. HPA filter

    candidates = filter_hpa(
        candidates,
        args.hpa
    )

    # 3. Epitope filter

    candidates = filter_epitopes(
        candidates,
        args.epitopes
    )

    # 4. Cancer sharing

    candidates = add_cancer_sharing(
        candidates,
        args.binary_matrix
    )

    # 5. Add antigen type

    candidates = add_antigen_type(
        candidates,
        args.merged_summed_genes
    )

    # 6. Final table

    save_results(
        candidates,
        args.output
    )


if __name__ == "__main__":
    main()
